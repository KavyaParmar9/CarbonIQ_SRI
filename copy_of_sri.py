"""## 4. Cement Emission Calculator Class

To standardize and modularize our calculations, we will implement a Python class `CementEmissionCalculator`. This class will encapsulate the logic for calculating total emissions, process emissions (from calcination), and fuel emissions, based on activity data and emission factors derived from industry benchmarks.
"""

class CementEmissionCalculator:
    """
    A class to calculate carbon emissions from cement production.
    Uses benchmark values from industry context for emission factors and ratios.
    """

    def __init__(self, clinker_ratio=0.72, emission_factor_cement=0.545,
                 calcination_share=0.65, fuel_combustion_share=0.35,
                 thermal_intensity_clinker_GJ_tonne=3.5,
                 electrical_intensity_cement_kWh_tonne=91):
        """
        Initializes the calculator with industry benchmark values.

        Args:
            clinker_ratio (float): Ratio of clinker in cement (e.g., 0.72 for 72%).
            emission_factor_cement (float): Total CO2 emissions per tonne of cement (tCO2/tonne cement).
                                            Average of 0.54-0.55 tCO2/tonne.
            calcination_share (float): Proportion of emissions from calcination (e.g., 0.65).
            fuel_combustion_share (float): Proportion of emissions from fuel combustion (e.g., 0.35).
            thermal_intensity_clinker_GJ_tonne (float): Thermal energy intensity per tonne of clinker (GJ/tonne clinker).
            electrical_intensity_cement_kWh_tonne (float): Electrical energy intensity per tonne of cement (kWh/tonne cement).
        """
        if not (0 <= clinker_ratio <= 1): raise ValueError("Clinker ratio must be between 0 and 1.")
        if not (0 <= calcination_share <= 1) or not (0 <= fuel_combustion_share <= 1): raise ValueError("Emission shares must be between 0 and 1.")
        if abs(calcination_share + fuel_combustion_share - 1.0) > 1e-6: print("Warning: Calcination and fuel combustion shares do not sum to 1.0. Normalizing...");

        # Normalizing if not summing to 1.0
        total_share = calcination_share + fuel_combustion_share
        self.calcination_share = calcination_share / total_share
        self.fuel_combustion_share = fuel_combustion_share / total_share

        self.clinker_ratio = clinker_ratio
        self.emission_factor_cement = emission_factor_cement
        self.thermal_intensity_clinker_GJ_tonne = thermal_intensity_clinker_GJ_tonne
        self.electrical_intensity_cement_kWh_tonne = electrical_intensity_cement_kWh_tonne

        # Derived emission factors for process and fuel based on overall emission factor
        self.emission_factor_calcination = self.emission_factor_cement * self.calcination_share
        self.emission_factor_fuel = self.emission_factor_cement * self.fuel_combustion_share

        print(f"CementEmissionCalculator initialized with:" \
              f"\n  Clinker Ratio: {self.clinker_ratio}" \
              f"\n  Total Emission Factor: {self.emission_factor_cement} tCO2/tonne cement" \
              f"\n  Calcination Share: {self.calcination_share:.1%}" \
              f"\n  Fuel Combustion Share: {self.fuel_combustion_share:.1%}" \
              f"\n  Process Emission Factor: {self.emission_factor_calcination:.3f} tCO2/tonne cement" \
              f"\n  Fuel Emission Factor: {self.emission_factor_fuel:.3f} tCO2/tonne cement")

    def calculate_total_emissions(self, cement_production_tonnes):
        """
        Calculates total CO2 emissions given cement production.
        Args:
            cement_production_tonnes (float): Amount of cement produced in tonnes.
        Returns:
            float: Total CO2 emissions in tonnes.
        """
        return cement_production_tonnes * self.emission_factor_cement

    def calculate_process_emissions(self, cement_production_tonnes):
        """
        Calculates CO2 emissions from calcination given cement production.
        Args:
            cement_production_tonnes (float): Amount of cement produced in tonnes.
        Returns:
            float: Process CO2 emissions in tonnes.
        """
        return cement_production_tonnes * self.emission_factor_calcination

    def calculate_fuel_emissions(self, cement_production_tonnes):
        """
        Calculates CO2 emissions from fuel combustion given cement production.
        Args:
            cement_production_tonnes (float): Amount of cement produced in tonnes.
        Returns:
            float: Fuel CO2 emissions in tonnes.
        """
        return cement_production_tonnes * self.emission_factor_fuel

    def calculate_thermal_energy_consumption(self, cement_production_tonnes):
        """
        Calculates thermal energy consumption given cement production.
        Args:
            cement_production_tonnes (float): Amount of cement produced in tonnes.
        Returns:
            float: Thermal energy consumption in GJ.
        """
        clinker_production_tonnes = cement_production_tonnes * self.clinker_ratio
        return clinker_production_tonnes * self.thermal_intensity_clinker_GJ_tonne

    def calculate_electrical_energy_consumption(self, cement_production_tonnes):
        """
        Calculates electrical energy consumption given cement production.
        Args:
            cement_production_tonnes (float): Amount of cement produced in tonnes.
        Returns:
            float: Electrical energy consumption in kWh.
        """
        return cement_production_tonnes * self.electrical_intensity_cement_kWh_tonne

print("CementEmissionCalculator class defined.")

