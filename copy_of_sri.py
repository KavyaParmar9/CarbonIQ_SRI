"""## 16. Semiconductor Emission Calculator Class

To standardize and modularize our calculations for the semiconductor industry, we will implement a Python class `SemiconductorEmissionCalculator`. This class will encapsulate the logic for calculating total emissions, and breaking them down conceptually into indirect (electricity), direct (process gases), and direct (fuel combustion) based on activity data and emission factors/intensities derived from industry benchmarks.
"""

class SemiconductorEmissionCalculator:
    """
    A class to calculate carbon emissions from semiconductor manufacturing.
    Uses benchmark values from industry context for emission factors and energy intensities.
    """

    def __init__(self, emission_factor_total=0.5, # Conceptual tCO2e per 'production unit' (e.g., per MUSD revenue or per kg silicon)
                 indirect_electricity_share=0.70,
                 direct_process_gases_share=0.20,
                 direct_fuel_combustion_share=0.10,
                 electrical_intensity_kwh_unit=50000): # Conceptual kWh per 'production unit'
        """
        Initializes the calculator with industry benchmark values for semiconductor.

        Args:
            emission_factor_total (float): Total CO2e emissions per conceptual 'production unit'.
            indirect_electricity_share (float): Proportion of emissions from indirect electricity consumption.
            direct_process_gases_share (float): Proportion of emissions from direct process gases.
            direct_fuel_combustion_share (float): Proportion of emissions from direct fuel combustion.
            electrical_intensity_kwh_unit (float): Electrical energy intensity per conceptual 'production unit' (kWh/unit).
        """
        if not (0 <= indirect_electricity_share <= 1) or \
           not (0 <= direct_process_gases_share <= 1) or \
           not (0 <= direct_fuel_combustion_share <= 1):
            raise ValueError("Emission shares must be between 0 and 1.")

        total_share = indirect_electricity_share + direct_process_gases_share + direct_fuel_combustion_share
        if abs(total_share - 1.0) > 1e-6:
            print("Warning: Semiconductor emission shares do not sum to 1.0. Normalizing...")
            self.indirect_electricity_share = indirect_electricity_share / total_share
            self.direct_process_gases_share = direct_process_gases_share / total_share
            self.direct_fuel_combustion_share = direct_fuel_combustion_share / total_share
        else:
            self.indirect_electricity_share = indirect_electricity_share
            self.direct_process_gases_share = direct_process_gases_share
            self.direct_fuel_combustion_share = direct_fuel_combustion_share

        self.emission_factor_total = emission_factor_total
        self.electrical_intensity_kwh_unit = electrical_intensity_kwh_unit

        print(f"SemiconductorEmissionCalculator initialized with:"
              f"\n  Total Emission Factor: {self.emission_factor_total} tCO2e/production unit"
              f"\n  Indirect Electricity Share: {self.indirect_electricity_share:.1%}"
              f"\n  Direct Process Gases Share: {self.direct_process_gases_share:.1%}"
              f"\n  Direct Fuel Combustion Share: {self.direct_fuel_combustion_share:.1%}"
              f"\n  Electrical Intensity: {self.electrical_intensity_kwh_unit} kWh/production unit")

    def calculate_total_emissions(self, production_units):
        """
        Calculates total CO2e emissions given a number of production units.
        Args:
            production_units (float): Number of conceptual production units.
        Returns:
            float: Total CO2e emissions in tonnes.
        """
        return production_units * self.emission_factor_total

    def calculate_indirect_electricity_emissions(self, production_units):
        """
        Calculates indirect CO2e emissions from electricity given production units.
        Args:
            production_units (float): Number of conceptual production units.
        Returns:
            float: Indirect CO2e emissions in tonnes.
        """
        return production_units * self.emission_factor_total * self.indirect_electricity_share

    def calculate_direct_process_gases_emissions(self, production_units):
        """
        Calculates direct CO2e emissions from process gases given production units.
        Args:
            production_units (float): Number of conceptual production units.
        Returns:
            float: Direct CO2e emissions in tonnes.
        """
        return production_units * self.emission_factor_total * self.direct_process_gases_share

    def calculate_direct_fuel_combustion_emissions(self, production_units):
        """
        Calculates direct CO2e emissions from fuel combustion given production units.
        Args:
            production_units (float): Number of conceptual production units.
        Returns:
            float: Direct CO2e emissions in tonnes.
        """
        return production_units * self.emission_factor_total * self.direct_fuel_combustion_share

    def calculate_electrical_energy_consumption(self, production_units):
        """
        Calculates total electrical energy consumption given production units.
        Args:
            production_units (float): Number of conceptual production units.
        Returns:
            float: Electrical energy consumption in kWh.
        """
        return production_units * self.electrical_intensity_kwh_unit

print("SemiconductorEmissionCalculator class defined.")

