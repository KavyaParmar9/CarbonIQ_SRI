"""## 10. Steel Emission Calculator Class

To standardize and modularize our calculations for the steel industry, we will implement a Python class `SteelEmissionCalculator`. This class will encapsulate the logic for calculating total emissions and, conceptually, energy consumption, based on activity data and emission factors/intensities derived from industry benchmarks.
"""

class SteelEmissionCalculator:
    """
    A class to calculate carbon emissions from steel production.
    Uses benchmark values from industry context for emission factors and energy intensities.
    """

    def __init__(self, emission_factor_steel=1.9, # tonnes CO2/tonne crude steel (integrated)
                 ironmaking_share=0.80,
                 steelmaking_share=0.10,
                 other_processes_share=0.10,
                 energy_intensity_steel_GJ_tonne=19): # GJ/tonne crude steel
        """
        Initializes the calculator with industry benchmark values for steel.

        Args:
            emission_factor_steel (float): Total CO2 emissions per tonne of crude steel (tCO2/tonne steel).
            ironmaking_share (float): Proportion of emissions from ironmaking (e.g., 0.80).
            steelmaking_share (float): Proportion of emissions from steelmaking (e.g., 0.10).
            other_processes_share (float): Proportion of emissions from other processes (e.g., 0.10).
            energy_intensity_steel_GJ_tonne (float): Energy intensity per tonne of crude steel (GJ/tonne steel).
        """
        if not (0 <= ironmaking_share <= 1) or not (0 <= steelmaking_share <= 1) or not (0 <= other_processes_share <= 1):
            raise ValueError("Emission shares must be between 0 and 1.")
        total_share = ironmaking_share + steelmaking_share + other_processes_share
        if abs(total_share - 1.0) > 1e-6:
            print("Warning: Steel emission shares do not sum to 1.0. Normalizing...")
            self.ironmaking_share = ironmaking_share / total_share
            self.steelmaking_share = steelmaking_share / total_share
            self.other_processes_share = other_processes_share / total_share
        else:
            self.ironmaking_share = ironmaking_share
            self.steelmaking_share = steelmaking_share
            self.other_processes_share = other_processes_share

        self.emission_factor_steel = emission_factor_steel
        self.energy_intensity_steel_GJ_tonne = energy_intensity_steel_GJ_tonne

        print(f"SteelEmissionCalculator initialized with:"
              f"\n  Total Emission Factor: {self.emission_factor_steel} tCO2/tonne steel"
              f"\n  Ironmaking Share: {self.ironmaking_share:.1%}"
              f"\n  Steelmaking Share: {self.steelmaking_share:.1%}"
              f"\n  Other Processes Share: {self.other_processes_share:.1%}"
              f"\n  Energy Intensity: {self.energy_intensity_steel_GJ_tonne} GJ/tonne steel")

    def calculate_total_emissions(self, steel_production_tonnes):
        """
        Calculates total CO2 emissions given steel production.
        Args:
            steel_production_tonnes (float): Amount of crude steel produced in tonnes.
        Returns:
            float: Total CO2 emissions in tonnes.
        """
        return steel_production_tonnes * self.emission_factor_steel

    def calculate_ironmaking_emissions(self, steel_production_tonnes):
        """
        Calculates CO2 emissions from ironmaking given steel production.
        Args:
            steel_production_tonnes (float): Amount of crude steel produced in tonnes.
        Returns:
            float: Ironmaking CO2 emissions in tonnes.
        """
        return steel_production_tonnes * self.emission_factor_steel * self.ironmaking_share

    def calculate_steelmaking_emissions(self, steel_production_tonnes):
        """
        Calculates CO2 emissions from steelmaking given steel production.
        Args:
            steel_production_tonnes (float): Amount of crude steel produced in tonnes.
        Returns:
            float: Steelmaking CO2 emissions in tonnes.
        """
        return steel_production_tonnes * self.emission_factor_steel * self.steelmaking_share

    def calculate_other_process_emissions(self, steel_production_tonnes):
        """
        Calculates CO2 emissions from other processes given steel production.
        Args:
            steel_production_tonnes (float): Amount of crude steel produced in tonnes.
        Returns:
            float: Other process CO2 emissions in tonnes.
        """
        return steel_production_tonnes * self.emission_factor_steel * self.other_processes_share

    def calculate_total_energy_consumption(self, steel_production_tonnes):
        """
        Calculates total energy consumption given steel production.
        Args:
            steel_production_tonnes (float): Amount of crude steel produced in tonnes.
        Returns:
            float: Total energy consumption in GJ.
        """
        return steel_production_tonnes * self.energy_intensity_steel_GJ_tonne

print("SteelEmissionCalculator class defined.")

